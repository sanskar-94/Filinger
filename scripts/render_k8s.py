"""Render the Kubernetes objects that are copies of files kept elsewhere in the repository.

1. infra/k8s/base/alerts.yaml: a PrometheusRule built from infra/monitoring/alerts.yml. That file stays the single
   source of truth: promtool unit tests run against it (alerts_test.yml) and the compose Prometheus loads it.
2. infra/k8s/base/experiment-config.yaml: a ConfigMap holding configs/experiment.json, mounted into the API at
   /config/experiment.json, so the experiment the cluster runs is the one reviewed in the repository.

Kustomize cannot read files outside its directory, hence the generated copies. CI re-renders them and fails on
any difference, so they can never drift from their sources.

    python scripts/render_k8s.py            # write both files
    python scripts/render_k8s.py --check    # exit 1 when a committed copy is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


class _Block(str):
    """A string dumped as a YAML literal block, so the embedded JSON stays readable in review."""


yaml.add_representer(_Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"),
                     Dumper=yaml.SafeDumper)


def _header(source: str) -> str:
    return f"# GENERATED by scripts/render_k8s.py from {source}. Edit that file instead.\n"


def alerts() -> str:
    source = "infra/monitoring/alerts.yml"
    groups = yaml.safe_load((ROOT / source).read_text())["groups"]
    rule = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "filings-lab-alerts", "labels": {"release": "kube-prometheus-stack"}},
        "spec": {"groups": groups},
    }
    return _header(source) + yaml.safe_dump(rule, sort_keys=False, width=200)


def experiment_config() -> str:
    source = "configs/experiment.json"
    text = (ROOT / source).read_text()
    json.loads(text)  # refuse to ship a config the service could not parse
    cm = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "experiment-config"},
          "data": {"experiment.json": _Block(text)}}
    return _header(source) + yaml.safe_dump(cm, sort_keys=False, width=200)


TARGETS = {
    "infra/k8s/base/alerts.yaml": alerts,
    "infra/k8s/base/experiment-config.yaml": experiment_config,
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for rel, render in TARGETS.items():
        out, path = render(), ROOT / rel
        if a.check:
            if not path.exists() or path.read_text() != out:
                stale.append(rel)
        else:
            path.write_text(out)
            print(f"wrote {rel}")
    if stale:
        print(f"stale: {', '.join(stale)}. Run python scripts/render_k8s.py", file=sys.stderr)
        return 1
    if a.check:
        print("generated Kubernetes objects match their sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
